// Builds shared/corpora/artworks.json once, offline.
//
// The Art Institute of Chicago API needs no key and sends CORS `*`, but we
// still bake a static file: 90 artworks is a dozen API calls we should not
// repeat on every page load, and pinning the set keeps demos reproducible.
import { writeFile } from 'node:fs/promises';

const UA = 'jev-instruments/0.1 (local experiment)';
const FIELDS = [
  'id', 'title', 'artist_title', 'date_display', 'date_end', 'medium_display',
  'artwork_type_title', 'department_title', 'place_of_origin', 'style_title',
  'classification_titles', 'image_id', 'is_public_domain', 'thumbnail',
].join(',');

// Spread the queries so the corpus is varied rather than 90 landscapes.
const QUERIES = [
  'portrait', 'landscape', 'still life', 'storm', 'river', 'city street',
  'sculpture', 'mother child', 'horse', 'flowers', 'night', 'interior room',
  'battle', 'self portrait', 'harbour ships', 'abstract', 'woodblock print',
  'dancer', 'winter snow', 'market',
];

const eraOf = (y) =>
  !y ? null : y < 1500 ? 'medieval' : y < 1700 ? 'renaissance'
    : y < 1800 ? 'baroque' : y < 1900 ? 'nineteenth_century'
    : y < 1945 ? 'early_modern' : 'contemporary';

// Tags exist only for the offline stub, same as the emoji corpus.
function tagsFor(a) {
  const t = new Set();
  const push = (s) => {
    if (!s) return;
    for (const w of String(s).toLowerCase().match(/[a-z]+/g) ?? []) {
      if (w.length > 3) t.add(w);
    }
  };
  push(a.artwork_type_title);
  // Departments are phrases like "Painting and Sculpture of Europe" — split
  // into words they tag every European painting as a sculpture.
  if (a.department_title) {
    t.add(a.department_title.toLowerCase().replace(/[^a-z]+/g, '_').replace(/^_|_$/g, ''));
  }
  push(a.style_title);
  push(a.medium_display);
  (a.classification_titles ?? []).forEach(push);
  push(a.title);
  const era = eraOf(a.date_end);
  if (era) t.add(era);
  if (/oil|canvas/i.test(a.medium_display ?? '')) t.add('painting');
  if (/bronze|marble|stone|wood/i.test(a.medium_display ?? '')) t.add('sculpture');
  if (/print|etching|lithograph|woodblock/i.test(a.medium_display ?? '')) t.add('print');
  return [...t].slice(0, 14);
}

async function search(q) {
  const url = `https://api.artic.edu/api/v1/artworks/search?q=${encodeURIComponent(q)}`
    + `&limit=12&fields=${FIELDS}`;
  const res = await fetch(url, { headers: { 'AIC-User-Agent': UA, 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${q}: ${res.status}`);
  const json = await res.json();
  return { data: json.data ?? [], iiif: json.config?.iiif_url ?? 'https://www.artic.edu/iiif/2' };
}

const seen = new Set();
const items = [];
let iiif = 'https://www.artic.edu/iiif/2';

for (const q of QUERIES) {
  try {
    const { data, iiif: base } = await search(q);
    iiif = base;
    for (const a of data) {
      // Only public-domain works with an actual image are usable.
      if (!a.is_public_domain || !a.image_id || seen.has(a.id)) continue;
      if (!a.title || !a.artist_title) continue;
      seen.add(a.id);
      items.push({
        id: `aic-${a.id}`,
        name: a.title.length > 62 ? `${a.title.slice(0, 60)}…` : a.title,
        sub: [a.artist_title, a.date_display].filter(Boolean).join(', '),
        thumb: `${iiif}/${a.image_id}/full/200,/0/default.jpg`,
        full: `${iiif}/${a.image_id}/full/843,/0/default.jpg`,
        alt: a.thumbnail?.alt_text ?? '',
        meta: {
          artist: a.artist_title, date: a.date_display,
          medium: a.medium_display, type: a.artwork_type_title,
          origin: a.place_of_origin, style: a.style_title,
        },
        tags: tagsFor(a),
      });
    }
  } catch (e) {
    console.warn(`  skipped "${q}": ${e.message}`);
  }
  await new Promise((r) => setTimeout(r, 350));
  process.stdout.write(`\r  collected ${items.length}…`);
}

const out = items.slice(0, 96);
// Written as .js, not .json: Node needs import attributes for JSON and Vite
// does not, so a plain module is the one form both import identically.
const body = `// Generated by scripts/build-artworks.mjs — do not edit by hand.
export default ${JSON.stringify({ source: 'Art Institute of Chicago (public domain)', items: out }, null, 1)};
`;
await writeFile(new URL('../shared/corpora/artworks.js', import.meta.url), body);
console.log(`\n✓ ${out.length} artworks → shared/corpora/artworks.js`);
